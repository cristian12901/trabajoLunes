public class Estudiante {
    String codigo, nombre, carrera;
    double notaDesarrollo, notaDefinitiva;

    public Estudiante(String codigo, String nombre, String carrera, double notaDesarrollo, double notaDefinitiva) {
        this.codigo = codigo;
        this.nombre = nombre;
        this.carrera = carrera;
        this.notaDesarrollo = notaDesarrollo;
        this.notaDefinitiva = notaDefinitiva;
    }
}